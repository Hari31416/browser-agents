"""Shared protocol schemas for provider registration, discovery, and chat relay."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CreateSessionResponse(BaseModel):
    """Session creation response with trusted session token."""

    session_token: str = Field(description="Opaque session authorization token")


class ProviderRegisterRequest(BaseModel):
    """Registration request for a model provider endpoint."""

    base_url: str = Field(description="Base URL for the OpenAI-compatible endpoint")
    api_key: Optional[str] = Field(
        default=None, description="Optional API key for authenticated endpoints"
    )
    models: Optional[List[str]] = Field(
        default=None,
        description="Optional manual list of model identifiers if discovery is unavailable",
    )


class ProviderResponse(BaseModel):
    """Response returned upon successful provider registration."""

    provider_id: str = Field(description="Session-scoped provider identifier")
    base_url: str = Field(description="Normalized endpoint base URL")
    has_api_key: bool = Field(description="Whether credentials are authenticated")
    discovered_models: List[str] = Field(
        default_factory=list, description="Models discovered from the upstream endpoint"
    )


class ModelDiscoveryResponse(BaseModel):
    """Model list response for a registered provider."""

    provider_id: str = Field(description="Session-scoped provider identifier")
    models: List[str] = Field(description="Discovered or manually configured models")
    supports_discovery: bool = Field(
        description="Whether models were fetched via upstream discovery"
    )


class ChatMessage(BaseModel):
    """Chat message schema for OpenAI-compatible conversations."""

    role: str = Field(description="Role: user, assistant, system, or tool")
    content: Optional[str] = Field(default=None, description="Text content")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(
        default=None, description="Tool calls generated by assistant"
    )
    tool_call_id: Optional[str] = Field(
        default=None, description="Tool call identifier when role is tool"
    )


class ChatRequest(BaseModel):
    """Chat generation request forwarded via relay."""

    provider_id: str = Field(description="Session-scoped provider identifier")
    model: str = Field(description="Model identifier")
    messages: List[ChatMessage] = Field(description="Conversation history")
    tools: Optional[List[Dict[str, Any]]] = Field(
        default=None, description="Tool specifications"
    )
    stream: bool = Field(default=True, description="Whether response should stream")


class RelayError(BaseModel):
    """Typed error envelope returned to the client without credential leaks."""

    error: str = Field(description="Standardized error code")
    message: str = Field(description="Human-readable description")
